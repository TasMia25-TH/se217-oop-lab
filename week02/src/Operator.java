public class Operator {
    public static void main(String[] args) {
        int x;
        x=5;
        System.out.println("current value is:" + x++ );
        System.out.println("current value is:" + ++x );

        x=5;
        System.out.println("current value is:" + x++ );
        System.out.println("current value is:" + ++x );
    }
    
}
